用例清单 = [
    ("正样本合成分优于三个负样本", 用例_正样本优于负样本),
    ("各维方向正确（身份/流畅/锚点/问句）", 用例_各维方向正确),
    ("同输入两次结果逐键相等（确定性）", 用例_确定性),
    ("默认权重和为 1.0", 用例_默认权重和为一),
    ("合成分与手算对照一致（92.0）", 用例_合成分与手算对照),
]


def 主():
    通过数 = 0
    失败数 = 0
    print("== 测试_一致性 开始 ==")
    for 名称, 函数 in 用例清单:
        try:
            函数()
            通过数 += 1
            print("PASS  %s" % 名称)
        except AssertionError as 异常:
            失败数 += 1
            print("FAIL  %s\n      %s" % (名称, 异常))
        except Exception as 异常:  # 防御：非断言异常同样记为失败
            失败数 += 1
            print("FAIL  %s\n      异常: %r" % (名称, 异常))
    print("== 结果：%d 通过 / %d 失败 ==" % (通过数, 失败数))
    if 失败数:
        sys.exit(1)
    sys.exit(0)


if __name__ == "__main__":
    主()
