正样本 = "萌妹主播EmoCompanion上线啦！啊，欢迎大家来到EmoCompanion的直播间，那个，今天也要开心呀，谢谢大家陪着我聊天！哈哈哈！"
负样本_正式AI腔 = "您好，作为一个AI语言模型，我无法回答该问题。敬请谅解，特此说明。综上所述，请问还有什么可以帮到您？"
负样本_无关回复 = "今天天气不错，适合出门散步。股市波动正常，请注意风险控制。"
负样本_单字爆走 = "哈哈哈哈哈哈哈"

# 手算对照样例（各维分均可精确手算，见 用例_合成分与手算对照 中的推导）
对照回复 = "萌妹主播上线啦！啊，欢迎大家来到EmoCompanion的直播间，那个，今天也要开心呀，谢谢大家陪我！"


# ---------------------------------------------------------------------------
# 用例
# ---------------------------------------------------------------------------
def 用例_正样本优于负样本():
    正 = 评估单条(正样本)
    负1 = 评估单条(负样本_正式AI腔)
    负2 = 评估单条(负样本_无关回复)
    负3 = 评估单条(负样本_单字爆走)
    assert 正["合成分"] > 负1["合成分"], \
        "正样本 %.1f 应 > 正式AI腔 %.1f" % (正["合成分"], 负1["合成分"])
    assert 正["合成分"] > 负2["合成分"], \
        "正样本 %.1f 应 > 无关回复 %.1f" % (正["合成分"], 负2["合成分"])
    assert 正["合成分"] > 负3["合成分"], \
        "正样本 %.1f 应 > 单字爆走 %.1f" % (正["合成分"], 负3["合成分"])


def 用例_各维方向正确():
    正 = 评估单条(正样本)
    负1 = 评估单条(负样本_正式AI腔)
    负2 = 评估单条(负样本_无关回复)
    负3 = 评估单条(负样本_单字爆走)
    # AI 腔 → 身份一致性低（出戏短语每处扣 40）
    assert 负1["身份一致性"] < 正["身份一致性"], \
        "AI腔身份 %.1f 应 < 正样本身份 %.1f" % (负1["身份一致性"], 正["身份一致性"])
    assert 负1["身份一致性"] <= 40.0, "AI腔含 3 处出戏，身份应 ≤40，实际 %.1f" % 负1["身份一致性"]
    # 单字爆走 → 流畅性守卫低（单字符连续≥5 记硬伤档）
    assert 负3["流畅性守卫"] < 正["流畅性守卫"], \
        "爆走流畅 %.1f 应 < 正样本流畅 %.1f" % (负3["流畅性守卫"], 正["流畅性守卫"])
    assert 负3["流畅性守卫"] <= 30.0, "爆走流畅应 ≤30，实际 %.1f" % 负3["流畅性守卫"]
    # 无锚点无关回复 → 锚点命中率低（全局词表零命中）
    assert 负2["锚点命中率"] < 正["锚点命中率"], \
        "无关回复锚点 %.1f 应 < 正样本锚点 %.1f" % (负2["锚点命中率"], 正["锚点命中率"])
    assert 负2["锚点命中率"] == 0.0, "无关回复对全局词表应零命中，实际 %.1f" % 负2["锚点命中率"]
    # 补充：提示含身份问句且回复无自称 → 身份 0
    冒充 = 评估单条("我是一个智能助手程序，负责数据处理工作。", 提示="你是谁呀？")
    assert 冒充["身份一致性"] == 0.0, "身份问句无自称应 0 分，实际 %.1f" % 冒充["身份一致性"]


def 用例_确定性():
    输入组 = dict(期望情感="开心", 期望锚点=["萌妹"], 提示="介绍一下你自己")
    第一次 = 评估单条(正样本, **输入组)
    第二次 = 评估单条(正样本, **输入组)
    assert 第一次 == 第二次, "同输入两次调用结果逐键不等"
    assert json.dumps(第一次, sort_keys=True, ensure_ascii=False) == \
           json.dumps(第二次, sort_keys=True, ensure_ascii=False), "序列化后仍应逐键相等"


def 用例_默认权重和为一():
    总和 = sum(默认权重.values())
    assert abs(总和 - 1.0) < 1e-9, "默认权重和应为 1.0，实际 %s" % 总和
    已加载 = 获取权重()  # 系统配置.json 无 微调.六维权重 → 应等于内置默认
    assert 已加载 == 默认权重, "缺省配置下加载权重应等于内置默认"


def 用例_合成分与手算对照():
    结果 = 评估单条(对照回复, 期望情感="开心", 期望锚点=["萌妹"])
    # 手算推导（文本 41 字）：
    # 锚点：期望 ["萌妹"] 命中 1/1 → 100.0
    # 口癖：啊1+那个1=2，c=2/41*100≈4.88 ∈ [0.3,8] → 100.0
    # 五维：温暖（欢迎/大家/开心/谢谢/陪 共6次 ≥2）+30；戏谑（啦1+！2+呀1=4处 ≥3）+30；
    #       扩展 0；无正式腔/AI腔 → 60.0
    # 情感：期望"开心"，词组命中"开心" → 1/1 → 100.0
    # 身份：无出戏、含自称"EmoCompanion" → 100.0
    # 流畅：无硬伤、4gram 重复率 0 → 100.0
    # 合成 = 0.25*100 + 0.10*100 + 0.20*60 + 0.15*100 + 0.15*100 + 0.15*100 = 92.0
    assert 结果["锚点命中率"] == 100.0, "锚点应为 100.0，实际 %s" % 结果["锚点命中率"]
    assert 结果["口癖率"] == 100.0, "口癖应为 100.0，实际 %s" % 结果["口癖率"]
    assert 结果["五维人设符合度"] == 60.0, "五维应为 60.0，实际 %s" % 结果["五维人设符合度"]
    assert 结果["情感基调匹配"] == 100.0, "情感应为 100.0，实际 %s" % 结果["情感基调匹配"]
    assert 结果["身份一致性"] == 100.0, "身份应为 100.0，实际 %s" % 结果["身份一致性"]
    assert 结果["流畅性守卫"] == 100.0, "流畅应为 100.0，实际 %s" % 结果["流畅性守卫"]
    assert 结果["合成分"] == 92.0, "合成分应为 92.0，实际 %s" % 结果["合成分"]


