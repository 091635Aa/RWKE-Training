def 互动模式(模型标识: str) -> int:
    """真人键入聊天：挂日记 State + 注入 + 延续对话（本地部署演示入口）。"""
    引擎 = RWKE引擎(模型标识)
    状态路径 = _RWKE_DIR / "states" / f"RoleB_状态_{模型标识}.pth"
    if 状态路径.exists():
        引擎.挂载日记状态(str(状态路径), 模型标识)
        print(f"[已挂载人设记忆：{状态路径.name}]")
    引擎.启用注入 = True
    引擎.启用捕获 = True
    print(f"[RWKE 本地聊天已启动] 模型={模型标识}（输入 exit 退出）\n")
    轮 = 0
    while True:
        try:
            消息 = input("你：").strip()
        except (EOFError, KeyboardInterrupt):
            break
        if not 消息 or 消息.lower() in ("exit", "quit", "q"):
            break
        轮 += 1
        回复 = 引擎.生成(消息, max_new_tokens=128, 保留池=True, 延续对话=(轮 > 1))
        print(f"RoleB：{回复}\n")
    return 0


def main() -> int:
    解析器 = argparse.ArgumentParser(description="RWKE 本地连续聊天实测（100 轮 × 三模式）")
    解析器.add_argument("--模型", default="RWKV7-World-1.5B")
    解析器.add_argument("--轮数", type=int, default=100)
    解析器.add_argument("--max-new-tokens", type=int, default=48, help="每轮回复上限（默认 48）")
    解析器.add_argument("--互动", action="store_true", help="真人键入聊天模式")
    解析器.add_argument("--数据", default=None, help="类人性检测的真人语料路径")
    解析器.add_argument("--偏置归一", action="store_true", help="缓和注入：偏置 RMS 归一（强度有界）")
    解析器.add_argument("--注入衰减", action="store_true", help="缓和注入：单轮前强后弱衰减")
    解析器.add_argument("--池容量", type=int, default=None, help="回响池容量上限（防质心僵化）")
    解析器.add_argument("--标签", default=None, help="输出文件名后缀（区分不同实验配置）")
    参数 = 解析器.parse_args()

    if 参数.互动:
        return 互动模式(参数.模型)

    from 测试_对比 import 加载提示数据
    try:
        对话数据 = 加载提示数据(参数.数据, 最小需求=90)
    except FileNotFoundError as e:
        print(f"警告：{e}（类人性评分将缺省）")
        对话数据 = []

    配置 = 引擎模块._读系统配置()
    条目 = 配置["模型矩阵"][参数.模型]
    模型路径 = Path(条目["路径"])
    if not 模型路径.is_absolute():
        模型路径 = _RWKE_DIR / 模型路径
    if not 模型路径.exists():
        print(f"错误：模型未就位：{模型路径}")
        return 2

    状态路径 = _RWKE_DIR / "states" / f"RoleB_状态_{参数.模型}.pth"
    引擎 = RWKE引擎(参数.模型, 偏置归一=参数.偏置归一, 注入衰减=参数.注入衰减,
                    池容量=参数.池容量)
    print(f"[引擎] {引擎.信息()}\n")
    print(f"[剧本] {参数.轮数} 轮日常聊天；第 30/60/100 轮为记忆突击测试\n")

    结果 = {}
    模式表 = [("A_裸", False, False), ("B_注入", True, False), ("C_挂日记+注入", True, True)]
    for 键, 注入, 挂载 in 模式表:
        if 挂载 and not 状态路径.exists():
            print(f"[跳过] {键}：日记 State 不存在（{状态路径}）")
            continue
        print(f"\n{'─' * 62}\n模式 {模式显示[键]}\n{'─' * 62}")
        if torch.cuda.is_available():
            torch.cuda.reset_peak_memory_stats()
        记录 = 跑连续对话(引擎, 键, 注入, 挂载, str(状态路径), 参数.轮数, 参数.max_new_tokens)
        评分结果 = 评分(记录, 对话数据)
        结果[键] = {"记录": 记录, "评分": 评分结果}
        if torch.cuda.is_available():
            结果[键]["峰值显存MB"] = round(torch.cuda.max_memory_allocated() / 1024 ** 2, 1)
        print(f"  ▶ {模式显示[键]} 总分：{评分结果['总分']}/100（{评分结果}）")
        gc.collect()
        if torch.cuda.is_available():
            torch.cuda.empty_cache()

    _结果目录.mkdir(exist_ok=True)
    文件名 = f"连续对话_{参数.模型}" + (f"_{参数.标签}" if 参数.标签 else "") + ".json"
    json路径 = _结果目录 / 文件名
    json路径.write_text(json.dumps(结果, ensure_ascii=False, indent=2), encoding="utf-8")

    if 结果:
        报告路径 = 生成演示报告(结果, 参数.模型, 参数.轮数)
        print(f"\n[报告] {报告路径}")
        print(f"[数据] {json路径}")
        print("\n各模式总分：")
        for k, v in 结果.items():
            print(f"  {模式显示[k]:　<14}{v['评分']['总分']}/100")
    return 0


if __name__ == "__main__":
    sys.exit(main())
