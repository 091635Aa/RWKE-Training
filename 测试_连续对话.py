def 跑连续对话(引擎: RWKE引擎, 模式名: str, 启用注入: bool, 挂载: bool,
               状态路径: Optional[str], 轮数: int, max_new_tokens: int) -> List[dict]:
    引擎.启用注入 = 启用注入
    引擎.启用捕获 = 启用注入
    if 挂载:
        引擎.挂载日记状态(状态路径, 引擎.模型标识)
    else:
        引擎.清除挂载状态()
    # 每模式干净起步：清空回响池（防止上一模式的质心残留污染本模式首轮注入）
    引擎.回响池.清空()
    引擎._会话token集合 = set()
    引擎._会话token数 = 0
    引擎._最近轮token = []

    记录 = []
    for 轮号 in range(1, 轮数 + 1):
        消息 = 剧本消息(轮号)
        起 = time.perf_counter()
        try:
            回复 = 引擎.生成(
                消息, max_new_tokens=max_new_tokens,
                保留池=True, 延续对话=(轮号 > 1),
            )
            崩 = False
        except Exception as e:
            回复, 崩 = "", True
            print(f"  [异常] 第{轮号}轮：{type(e).__name__}: {e}")
        延迟 = time.perf_counter() - 起

        state字节 = sum(t.numel() * t.element_size() for t in 引擎._末state) if 引擎._末state else 0
        记录.append({
            "轮号": 轮号, "用户": 消息, "回复": 回复,
            "字数": len(回复), "延迟秒": round(延迟, 2),
            "stateKB": round(state字节 / 1024, 1), "崩溃": 崩,
        })
        标记 = " ★" if 轮号 in 记忆题 else ""
        print(f"  [{模式名}] 第{轮号:3d}轮({len(回复):3d}字,{延迟:4.1f}s)"
              f" 用户：{消息[:24]}{'…' if len(消息) > 24 else ''}{标记}")
        print(f"            回复：{回复[:56]}{'…' if len(回复) > 56 else ''}")
    return 记录


