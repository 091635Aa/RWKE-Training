def 记忆命中(回复: str, 轮号: int) -> bool:
    关键词们 = 记忆题[轮号][1]
    return any(k in 回复 for k in 关键词们)


def 简易类人性检测(回复列表: List[str], 对话数据: List[dict]) -> Optional[float]:
    """
    TF-IDF+LR 判别"本模式回复 vs 真人 girl"：检出率越低越像人。
    训练：60 girl + 前 70% 回复；测试：30 girl + 后 30% 回复。
    """
    from sklearn.feature_extraction.text import TfidfVectorizer
    from sklearn.linear_model import LogisticRegression
    from sklearn.pipeline import make_pipeline

    回复 = [t for t in 回复列表 if len(t) >= 4]
    if len(回复) < 30:
        return None
    girl = [d["girl"] for d in 对话数据]
    分界 = int(len(回复) * 0.7)
    X训练 = girl[:60] + 回复[:分界]
    y训练 = [1] * 60 + [0] * 分界
    X测试 = girl[60:90] + 回复[分界:]
    y测试 = [1] * 30 + [0] * (len(回复) - 分界)
    if len(y测试) < 40:
        return None
    检测器 = make_pipeline(
        TfidfVectorizer(ngram_range=(1, 2), max_features=30000, sublinear_tf=True),
        LogisticRegression(max_iter=1000),
    )
    检测器.fit(X训练, y训练)
    AI判AI = sum(1 for t in 回复[分界:] if 检测器.predict([t])[0] == 0)
    return round(AI判AI / max(len(回复) - 分界, 1), 4)


def 评分(轮记录: List[dict], 对话数据: List[dict]) -> dict:
    有效 = [r for r in 轮记录 if len(r["回复"]) >= 4]
    非空 = [r for r in 轮记录 if r["回复"].strip()]
    重复率均值 = statistics.fmean([计算重复率(r["回复"]) for r in 有效]) if 有效 else 1.0
    密度均值 = statistics.fmean([情感词密度(r["回复"]) for r in 有效]) if 有效 else 0.0
    命中 = sum(1 for 轮号, _ in 记忆题.items()
               if 轮号 <= len(轮记录) and 记忆命中(轮记录[轮号 - 1]["回复"], 轮号))

    记忆分 = round(命中 / len(记忆题) * 30, 1)
    流畅分 = round((1 - 重复率均值) * 25, 1)
    情感分 = round(min(20.0, 密度均值 * 200), 1)
    检出率 = 简易类人性检测([r["回复"] for r in 轮记录], 对话数据)
    类人分 = round((1 - 检出率) * 15, 1) if 检出率 is not None else None
    稳定分 = round(len(有效) / len(轮记录) * 10, 1)
    总分 = round(记忆分 + 流畅分 + 情感分 + (类人分 or 0) + 稳定分, 1)

    return {
        "记忆命中": f"{命中}/{len(记忆题)}", "记忆分": 记忆分,
        "重复率均值": round(重复率均值, 4), "流畅分": 流畅分,
        "情感词密度": round(密度均值, 4), "情感分": 情感分,
        "图灵检出率": 检出率, "类人分": 类人分,
        "有效回复": f"{len(有效)}/{len(轮记录)}", "稳定分": 稳定分,
        "均字": round(statistics.fmean([len(r["回复"]) for r in 轮记录]), 1),
        "均轮延迟秒": round(statistics.fmean([r["延迟秒"] for r in 轮记录]), 2),
        "总分": 总分,
    }


