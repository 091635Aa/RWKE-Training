def _抽取分段(数据: dict, 文件名: str) -> list:
    """打标 JSON → 统一分段列表 [{transcript, 情感标签, 话题, 话题标签}]；失败返回空。"""
    try:
        分段列表 = []
        原分段 = 数据.get("时间轴分段") or []
        if isinstance(原分段, list) and 原分段:
            for seg in 原分段:
                if not isinstance(seg, dict):
                    continue
                分段列表.append({
                    "transcript": str(seg.get("transcript") or "").strip(),
                    "情感标签": [str(t) for t in (seg.get("情感标签") or [])][:4],
                    "话题": str(seg.get("话题") or seg.get("段落类型") or "直播日常").strip(),
                    "话题标签": [str(t) for t in (seg.get("话题标签") or [])][:4],
                })
        if not 分段列表:
            全文 = str(数据.get("transcript") or "").strip()
            if not 全文:
                return []
            分段列表 = [{
                "transcript": 全文,
                "情感标签": [str(t) for t in (数据.get("情感标签") or 数据.get("情绪标签") or [])][:4],
                "话题": str((数据.get("主题标签") or ["直播日常"])[0]).strip(),
                "话题标签": [str(t) for t in (数据.get("主题标签") or [])][:4],
            }]
        return 归一化对象([s for s in 分段列表 if s["transcript"]])
    except Exception:
        return []


def _取关键词(分段: dict) -> str:
    """从锚点词表+话题标签提取一个可用关键词（无则空串）。"""
    全文 = 分段["transcript"]
    for w in _锚点词表:
        if w in 全文:
            return w
    for w in 分段.get("话题标签", []):
        if 1 < len(w) <= 6 and w not in ("互动", "欢迎语", "直播结束", "观众支持"):
            return w
    return ""


def _取情绪词(情感标签: list, 序号: int, rng: random.Random) -> str:
    for t in 情感标签:
        if t in _情感词:
            词组 = _情感词[t]
            return 词组[序号 % len(词组)] if 序号 else rng.choice(词组)
    return "开心"


def _取转录片段(transcript: str, rng: random.Random) -> str:
    """从 transcript 取一个 8-30 字的短句供成年日记化用。"""
    子句 = [c.strip() for c in re.split(r"[。？！，]", transcript) if 8 <= len(c.strip()) <= 30]
    if 子句:
        return 子句[rng.randrange(len(子句))]
    return transcript[:30].strip()


