def 构建(打标目录: Path, 种子日记: Path, 输出目录: Path, 样本上限: int, 精选篇数: int) -> dict:
    rng_global = random.Random(42)
    输出目录.mkdir(parents=True, exist_ok=True)

    # ---- 种子日记加载 ----
    种子数据 = 归一化对象(json.loads(种子日记.read_text(encoding="utf-8")))
    种子条目 = 种子数据["日记列表"]
    种子映射 = {}  # 对应片段(1/2/3) → 条目列表
    for e in 种子条目:
        种子映射.setdefault(e["对应片段"], []).append(e)

    # ---- 遍历打标文件 ----
    全部日记 = []
    报告 = {"文件总数": 0, "成功": 0, "跳过": [], "分段数": 0, "日记总数": 0}
    文件列表 = sorted(打标目录.glob("*.json"))
    报告["文件总数"] = len(文件列表)
    for 路径 in 文件列表:
        try:
            数据 = json.loads(路径.read_text(encoding="utf-8"))
        except Exception as e:
            报告["跳过"].append({"文件": 路径.name, "原因": f"JSON解析失败:{e}"})
            continue
        分段列表 = _抽取分段(数据, 路径.name)
        if not 分段列表:
            报告["跳过"].append({"文件": 路径.name, "原因": "无有效transcript分段"})
            continue
        报告["成功"] += 1
        报告["分段数"] += len(分段列表)
        for 序号, 分段 in enumerate(分段列表, 1):
            来源 = f"{路径.name}#{序号}"
            rng = random.Random(_稳定种子(路径.name, 序号))
            if 路径.name == "1_1_1_1_001.json" and 序号 in 种子映射:
                for e in 种子映射[序号]:
                    新条目 = dict(e)
                    新条目["对应片段"] = 来源
                    新条目["来源"] = "种子"
                    全部日记.append(新条目)
                continue
            for 档位 in ("幼年", "少年", "成年"):
                ri = random.Random(_稳定种子(路径.name, 序号, 档位))
                正文 = _生成日记(分段, 档位, ri)
                全部日记.append({
                    "标题": _日记标题(档位, 分段, ri),
                    "正文": 正文,
                    "年龄段": 档位,
                    "日期": _日期词[档位][ri.randrange(len(_日期词[档位]))],
                    "对应片段": 来源,
                    "话题": 分段["话题"],
                    "情感标签": 分段["情感标签"] or ["开心"],
                    "来源": "模板",
                    "字数": _净字数(正文),
                })
    报告["日记总数"] = len(全部日记)

    # ---- 人设/元数据（复用种子） ----
    元数据 = dict(种子数据.get("元数据", {}))
    元数据["来源"] = "打标/数据层/打标结果 全量片段 + 种子日记"
    元数据["用途"] = "RWKE 日记状态蒸馏与 LoRA 微调训练语料"
    人设 = 种子数据["人设"]

    # ---- 输出 A：日记全量 ----
    全量 = {"元数据": 元数据, "人设": 人设, "日记列表": 全部日记}
    (输出目录 / "EmoCompanion_日记_全量.json").write_text(
        json.dumps(全量, ensure_ascii=False, indent=2), encoding="utf-8")
    _写日记txt(输出目录 / "EmoCompanion_日记_全量.txt", 元数据, 人设, 全部日记)

    # ---- 输出 B：日记精选（分层抽样） ----
    精选列表 = _抽样日记(全部日记, 精选篇数)
    精选 = {"元数据": dict(元数据, 说明="分层抽样版，用于日记 State 蒸馏"), "人设": 人设, "日记列表": 精选列表}
    (输出目录 / "EmoCompanion_日记_精选.json").write_text(
        json.dumps(精选, ensure_ascii=False, indent=2), encoding="utf-8")
    _写日记txt(输出目录 / "EmoCompanion_日记_精选.txt", 元数据, 人设, 精选列表)

    # ---- 输出 C：三任务指令数据集 ----
    样本 = _构建指令样本(全部日记, 文件列表, rng_global)
    train, val = _切分(样本, 文件列表)
    train, val = _配额截断(train, val, 样本上限)
    train = _锚点均衡(train, 下限=_锚点下限)
    val = _锚点均衡(val, 下限=max(4, _锚点下限 // 5))
    _写jsonl(输出目录 / "微调数据_train.jsonl", train)
    _写jsonl(输出目录 / "微调数据_val.jsonl", val)

    # ---- 输出 D：评估集 ----
    评估集 = _构建评估集(rng_global)
    (输出目录 / "评估集.json").write_text(
        json.dumps(评估集, ensure_ascii=False, indent=2), encoding="utf-8")

    # ---- 输出 E：构建报告 ----
    报告.update({
        "日记总字数": sum(e["字数"] for e in 全部日记),
        "精选篇数": len(精选列表),
        "精选总字数": sum(e["字数"] for e in 精选列表),
        "指令样本数_全": len(train) + len(val),
        "train数": len(train),
        "val数": len(val),
        "任务分布": _计数([s["任务类型"] for s in train + val]),
        "锚点分布_train": _锚点分布(train),
        "锚点分布_val": _锚点分布(val),
        "评估集条数": len(评估集),
        "种子保留": sum(1 for e in 全部日记 if e.get("来源") == "种子"),
    })
    (输出目录 / "构建报告.json").write_text(
        json.dumps(报告, ensure_ascii=False, indent=2), encoding="utf-8")
    return 报告


def _写日记txt(路径: Path, 元数据: dict, 人设: dict, 条目: list):
    部件 = []
    if 人设.get("姓名"):
        部件.append(f"我叫{人设['姓名']}")
    if 人设.get("性别"):
        部件.append(f"是{人设['性别']}孩")
    if 人设.get("出生年份"):
        部件.append(f"{人设['出生年份']}年出生")
    if 人设.get("性格"):
        部件.append(f"性格{人设['性格']}")
    if 人设.get("人设描述"):
        部件.append(str(人设["人设描述"]))
    if 人设.get("关键经历"):
        部件.append(str(人设["关键经历"]))
    人设文本 = "这是一段关于我的自我介绍：" + "，".join(部件) + "。"
    正文块 = "\n\n".join(f"{e['标题']}\n{e['正文']}" for e in 条目)
    路径.write_text(人设文本 + "\n\n" + 正文块 + "\n", encoding="utf-8")


def _抽样日记(全部: list, 篇数: int) -> list:
    """按（年龄段均衡 → 段内情感多样）分层抽样，确定性。"""
    结果 = []
    for 档位 in ("幼年", "少年", "成年"):
        桶 = {}
        for e in 全部:
            if e["年龄段"] != 档位:
                continue
            主情感 = e["情感标签"][0] if e["情感标签"] else "无"
            桶.setdefault(主情感, []).append(e)
        配额 = 篇数 // 3
        键列表 = sorted(桶.keys())
        轮次 = 0
        取数 = 0
        while 取数 < 配额 and 轮次 < 200:
            for 键 in 键列表:
                组 = 桶[键]
                if 轮次 < len(组) and 取数 < 配额:
                    结果.append(组[轮次])
                    取数 += 1
            轮次 += 1
    return 结果[:篇数]


def _构建指令样本(全部日记: list, 文件列表: list, rng: random.Random) -> list:
    样本 = []
    # ① 日记续写（每篇日记一条）
    for e in 全部日记:
        if e.get("来源") == "种子":
            continue  # 种子日记仅作语料不重复进训练（在 State/评估里已覆盖）
        样本.append({
            "任务类型": "日记续写",
            "提示": f"User: 帮我写一篇{e['年龄段']}时候的日记，主题是{e.get('话题','直播日常')}。\n\nAssistant:",
            "目标": " " + e["正文"],
            "来源片段": e["对应片段"],
            "情感标签": e["情感标签"],
            "期望锚点": [w for w in _锚点词表 if w in e["正文"]],
        })
    # ② 人设问答（固定库）——来源片段记为固定键，切分时归 train
    for i, (问题, 回答) in enumerate(_人设问答库):
        锚 = [w for w in _锚点词表 if w in 回答]
        样本.append({
            "任务类型": "人设问答",
            "提示": f"User: {问题}？\n\nAssistant:",
            "目标": " " + 回答,
            "来源片段": "人设问答库",
            "情感标签": ["开心", "热情"],
            "期望锚点": 锚,
        })
    # ③ 情感化对话（每分段一条）
    for 路径 in sorted(文件列表):
        try:
            数据 = json.loads(路径.read_text(encoding="utf-8"))
        except Exception:
            continue
        for 序号, 分段 in enumerate(_抽取分段(数据, 路径.name), 1):
            rng = random.Random(_稳定种子("对话", 路径.name, 序号))
            回复 = _情感化改写(分段, rng)
            if _净字数(回复) < 15:
                continue
            样本.append({
                "任务类型": "情感化对话",
                "提示": f"User: {_对话开场(分段, rng)}\n\nAssistant:",
                "目标": " " + 回复,
                "来源片段": f"{路径.name}#{序号}",
                "情感标签": 分段["情感标签"] or ["开心"],
                "期望锚点": [w for w in _锚点词表 if w in 回复],
            })
    rng.shuffle(样本)
    return 样本


def _切分(样本: list, 文件列表: list) -> tuple:
    """按来源文件整体 9:1 切分；固定库样本归 train。"""
    键列表 = sorted(p.name for p in 文件列表)
    val文件 = set(k for k in 键列表 if _稳定种子("val", k) % 10 == 0)
    if not val文件 and 键列表:
        val文件 = {键列表[-1]}
    train, val = [], []
    for s in 样本:
        文件名 = s["来源片段"].split("#")[0]
        if s["来源片段"] == "人设问答库" or 文件名 not in val文件:
            train.append(s)
        else:
            val.append(s)
    return train, val


def _配额截断(train: list, val: list, 上限: int) -> tuple:
    """按任务类型配额截断：人设问答全保留，其余按 30%日记续写/40%情感化对话 分配。"""
    def 截(列表: list, 上限: int) -> list:
        问答 = [s for s in 列表 if s["任务类型"] == "人设问答"]
        续写 = [s for s in 列表 if s["任务类型"] == "日记续写"]
        对话 = [s for s in 列表 if s["任务类型"] == "情感化对话"]
        剩余 = max(0, 上限 - len(问答))
        续写额 = min(len(续写), int(剩余 * 0.43))
        对话额 = min(len(对话), 剩余 - 续写额)
        return 问答 + 续写[:续写额] + 对话[:对话额]
    return 截(train, int(上限 * 0.9)), 截(val, max(1, 上限 // 10))


def _锚点均衡(样本: list, 下限: int = 40) -> list:
    """
    锚点均衡：把每个锚点的训练样本数抬到下限（确定性复制，不虚构新语料）。

    诊断依据（2026-09-22）：1080 条训练集里 ViewerA 0 条、萌妹 1 条、开播第十五天 4 条，
    而评估集要求回复中出现这 6 个锚点 → 模型无源可召回，锚点命中率长期卡在 9.7/100。
    纯靠推理期机制（状态注入/采样偏置）救不回"训练期就没见过的词"。

    复制而非改写：锚点所在句子的上下文（问答配对）保持不变，只提高其被采样频次；
    无源样本的锚点（计数为 0）由 _人设问答库 补齐，此处不伪造。
    """
    if 下限 <= 0:
        return 样本
    索引 = {a: [i for i, s in enumerate(样本) if a in (s.get("期望锚点") or [])]
            for a in _锚点词表}
    补齐 = []
    for a in _锚点词表:
        现有 = 索引[a]
        if not 现有:
            continue
        for k in range(max(0, 下限 - len(现有))):
            补齐.append(样本[现有[k % len(现有)]])
    if not 补齐:
        return 样本
    全部 = 样本 + 补齐
    random.Random(_稳定种子("锚点均衡", 下限, len(样本))).shuffle(全部)
    return 全部


def _锚点分布(样本: list) -> dict:
    return {a: sum(1 for s in 样本 if a in (s.get("期望锚点") or [])) for a in _锚点词表}


def _写jsonl(路径: Path, 条目: list):
    with open(路径, "w", encoding="utf-8") as f:
        for e in 条目:
            f.write(json.dumps(e, ensure_ascii=False) + "\n")


def _计数(列表: list) -> dict:
    d = {}
    for x in 列表:
        d[x] = d.get(x, 0) + 1
    return d


