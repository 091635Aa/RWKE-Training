def _调控(句子: list, 区间: tuple, 补句池: list, rng: random.Random) -> str:
    """拼句后按去空白字数调控到区间内（先补后裁；补句先取未用，耗尽后循环复用但禁连续重复）。"""
    未用 = list(range(len(补句池)))
    rng.shuffle(未用)
    while _净字数("".join(句子)) < 区间[0] and 补句池:
        if 未用:
            i = 未用.pop()
        else:
            i = rng.randrange(len(补句池))
            if 补句池[i] == 句子[-1] and len(补句池) > 1:  # 禁连续重复
                i = (i + 1) % len(补句池)
        句子.append(补句池[i])
    while _净字数("".join(句子)) > 区间[1] and len(句子) > 2:
        句子.pop()
    文本 = "".join(句子)
    # 超长兜底：从末尾整句删至达标（保底 2 句）
    while _净字数(文本) > 区间[1] and 文本.count("。") + 文本.count("！") + 文本.count("？") > 2:
        文本 = re.sub(r"[^。！？]*[。！？]$", "", 文本)
    if _净字数(文本) > 区间[1]:  # 仍超：硬截到区间上限（保句末标点）
        文本 = 文本[: 区间[1] - 1]
        if not 文本.endswith(("。", "！", "？", "啦", "呀")):
            文本 += "。"
    return 文本


def _生成日记(分段: dict, 档位: str, rng: random.Random) -> str:
    区间 = _字数区间[档位]
    关键词 = _取关键词(分段)
    情感词 = _取情绪词(分段["情感标签"], 0, rng)
    if 档位 == "幼年":
        句子 = [
            _幼年池["开头"][rng.randrange(len(_幼年池["开头"]))].format(
                kw事件=_kw事件(关键词, rng), kw=关键词 or "新鲜事"),
            _幼年池["感觉"][rng.randrange(len(_幼年池["感觉"]))].format(emo=情感词),
            _幼年池["氛围"][rng.randrange(len(_幼年池["氛围"]))],
            _幼年池["衰减"][rng.randrange(len(_幼年池["衰减"]))],
        ]
        return _调控(句子, 区间, _幼年补句, rng)
    if 档位 == "少年":
        场景池 = ["{kw场景}".format(kw场景=_kw场景(关键词, _kw场景少, rng))]
        句子 = [
            _少年池["开头"][rng.randrange(len(_少年池["开头"]))].format(
                kw场景=场景池[0], kw=关键词 or "新东西"),
            _少年池["细节"][rng.randrange(len(_少年池["细节"]))],
            _少年池["内心"][rng.randrange(len(_少年池["内心"]))].format(emo=情感词),
            _少年池["收束"][rng.randrange(len(_少年池["收束"]))],
        ]
        文本 = _调控(句子, 区间, _少年补句, rng)
        if "那个" not in 文本 and "啊" not in 文本:  # 口癖保底：替换式插入
            文本 = 文本.replace("这件事", "那个这件事", 1) if "这件事" in 文本 else 文本[:-1] + "啊。"
        return 文本
    # 成年
    片段 = _取转录片段(分段["transcript"], rng)
    日期短 = rng.choice(["二十二岁", "二十三岁"])
    句子 = [
        _成年池["开头"][rng.randrange(len(_成年池["开头"]))].format(日期短=日期短),
        _成年池["场景"][rng.randrange(len(_成年池["场景"]))].format(
            kw场景=_kw场景(关键词, _kw场景成, rng), kw=关键词 or "新日子"),
        _成年池["化用"][rng.randrange(len(_成年池["化用"]))].format(transcript=片段),
        _成年池["情感"][rng.randrange(len(_成年池["情感"]))].format(emo=情感词),
        _成年池["反思"][rng.randrange(len(_成年池["反思"]))],
    ]
    文本 = _调控(句子, 区间, _成年补句, rng)
    if "那个" not in 文本 and "啊" not in 文本:
        文本 = 文本.replace("我", "那个我", 1) if 文本.startswith("我") else "那个，" + 文本
    return 文本


def _日记标题(档位: str, 分段: dict, rng: random.Random) -> str:
    关键词 = _取关键词(分段)
    主题 = 关键词 or (分段["话题"][:6] if 分段["话题"] else "直播日常")
    短语池 = [
        f"{主题}的那天", f"关于{主题}", f"{主题}的小事", f"记得{主题}",
        f"{主题}来了", f"{主题}进行时",
    ]
    年龄 = _年龄词[档位][rng.randrange(len(_年龄词[档位]))]
    return f"{年龄}·{短语池[rng.randrange(len(短语池))]}"


