def 自检(输出目录: Path, 种子日记: Path) -> bool:
    全过 = True

    def 检查(名称: str, 通过: bool, 明细: str = ""):
        nonlocal 全过
        全过 &= 通过
        print(f"  [{'PASS' if 通过 else 'FAIL'}] {名称}" + (f"（{明细}）" if 明细 else ""))

    全量 = json.loads((输出目录 / "EmoCompanion_日记_全量.json").read_text(encoding="utf-8"))
    条目 = 全量["日记列表"]

    总字数 = sum(e["字数"] for e in 条目)
    检查("日记全量总字数≥5000", 总字数 >= 5000, f"{总字数}字")

    越界 = [e for e in 条目 if not (_字数区间[e["年龄段"]][0] <= _净字数(e["正文"]) <= _字数区间[e["年龄段"]][1])]
    检查("三档字数区间达标率100%", not 越界, f"越界{len(越界)}篇" if 越界 else f"{len(条目)}篇全达标")

    正文全集 = "".join(e["正文"] for e in 条目)
    缺失 = [w for w in _必查事件词 if w not in 正文全集]
    检查("核心事件词100%覆盖", not 缺失, f"缺失:{缺失}" if 缺失 else "8/8")

    空样本 = [e for e in 条目 if not e["正文"].strip()]
    检查("日记无空样本", not 空样本)

    train行 = (输出目录 / "微调数据_train.jsonl").read_text(encoding="utf-8").splitlines()
    val行 = (输出目录 / "微调数据_val.jsonl").read_text(encoding="utf-8").splitlines()
    train源 = {json.loads(l)["来源片段"].split("#")[0] for l in train行 if l}
    val源 = {json.loads(l)["来源片段"].split("#")[0] for l in val行 if l} - {"人设问答库"}
    交集 = train源 & val源
    检查("train/val来源文件无交集", not 交集, f"交集{len(交集)}" if 交集 else f"train={len(train行)} val={len(val行)}")

    空行 = [l for l in train行 + val行 if l and not json.loads(l)["目标"].strip()]
    检查("指令数据无空样本", not 空行)

    种子数据 = 归一化对象(json.loads(种子日记.read_text(encoding="utf-8")))
    缺种子 = [e["标题"] for e in 种子数据["日记列表"]
             if not any(x["正文"] == e["正文"] and x["标题"] == e["标题"] for x in 条目)]
    检查("种子日记9篇原样保留", not 缺种子, f"缺失:{缺种子}" if 缺种子 else "9/9")

    评估集 = json.loads((输出目录 / "评估集.json").read_text(encoding="utf-8"))
    锚覆盖 = {w: sum(1 for x in 评估集 if w in x["期望锚点"]) for w in ["天鹅之梦", "萌妹", "ViewerA", "开播第十五天"]}
    检查("评估集核心锚点各≥2条", all(v >= 2 for v in 锚覆盖.values()), str(锚覆盖))
    检查("评估集条数30-50", 30 <= len(评估集) <= 50, f"{len(评估集)}条")

    print(f"== 自检{'通过' if 全过 else '未通过'} ==")
    return 全过


