def _情感化改写(分段: dict, rng: random.Random) -> str:
    """transcript → 第一人称回复（清理 + 口癖兜底）。

    名字变体归一已在 语料纠错.归一化文本 里统一完成（分段入口处已归一），
    此处不再做局部替换，避免多处口径不一致。
    """
    文本 = re.sub(r"\s+", "", 分段["transcript"])
    文本 = 文本.rstrip("。？！") + "。"
    if "那个" not in 文本 and "啊" not in 文本:
        文本 = 文本.replace("我", "我啊，", 1)
    尾句 = rng.choice(["你们说是不是？", "就这么定了啊！", "谢谢你听我说完呀。"])
    return 文本 + 尾句


