# -*- coding: utf-8 -*-
"""从 注入策略_*.json 生成综合对比报告（含项目盘点、条纹分析、策略推荐）。"""
import json
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8", errors="replace")

_RWKE = Path(r"<workspace>/RWKE")


def 载入(模型):
    p = _RWKE / "results" / f"注入策略_{模型}.json"
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def 策略行(r, 基线指数):
    return (f"| {r['名称']} | {r['情感能力指数']} | {r['情感能力增幅%']}% "
            f"| {r['条纹率']} | {r['有效回复率']:.0%} | {r['均字']} | {r['均轮延迟秒']}s |")


def 模型节(数据, 标题):
    基线指数 = 数据["基线指数"]
    L = [f"## {标题}\n"]
    L.append("| 策略 | 情感指数/千字 | 情感增幅 | 条纹率↓ | 有效回复 | 均字 | 轮耗时 |")
    L.append("|---|---|---|---|---|---|---|")
    for r in 数据["策略"]:
        L.append(策略行(r, 基线指数))
    if 数据.get("标定记录"):
        L.append("\n有界自动标定（λ 爬坡，达标即停，最多 3 档）：\n")
        L.append("| 尝试 | 情感指数 | 增幅 | 条纹率 | 有效回复 |")
        L.append("|---|---|---|---|---|")
        for m in 数据["标定记录"]:
            L.append(f"| {m['名称']} (λ={m['λ']}) | {m['情感能力指数']} | {m['增幅%']}% "
                     f"| {m['条纹率']} | {m['有效回复率']} |")
    return L


