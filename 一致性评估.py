#   ② 双词共现：多词锚点允许被口语拆开，但要求拆开的词彼此紧邻（窗口见下），
#      避免"开播…很久以后…第十五天"这种偶然同现。
# v1/v2 均保留：v2 为当前默认，历史批次结果 JSON 用 评锚点(口径="v1") 可复算。
锚点口径默认 = "v2"
锚点别名 = {"EmoCompanion": "EmoCompanion"}
锚点共现表 = {"开播第十五天": (("开播", "第十五天"), 8)}


def _别名归一(文本: str) -> str:
    for 旧, 新 in 锚点别名.items():
        文本 = 文本.replace(旧, 新)
    return 文本


def 锚点命中(回复: str, 锚点: str, 口径: str = 锚点口径默认) -> bool:
    """单锚点是否命中（口径 v1=子串；v2=子串 + 同音别名 + 双词紧邻共现）。"""
    if not 锚点 or not 回复:
        return False
    if 锚点 in 回复:
        return True
    if 口径 != "v2":
        return False
    规 = _别名归一(回复)
    目标 = _别名归一(锚点)
    if 目标 in 规:
        return True
    共现 = 锚点共现表.get(锚点)
    if not 共现:
        return False
    (词甲, 词乙), 窗口 = 共现
    甲位 = [m.start() for m in re.finditer(re.escape(词甲), 规)]
    乙位 = [m.start() for m in re.finditer(re.escape(词乙), 规)]
    if not 甲位 or not 乙位:
        return False
    return min(abs(a - b) for a in 甲位 for b in 乙位) <= 窗口


def 评锚点(回复, 期望锚点=None, 口径: str = 锚点口径默认):
    """维度 1：期望锚点命中比例 ×100；未给期望锚点则用全局词表（见 锚点命中）。"""
    无期望 = 期望锚点 is None or 期望锚点 == "" or (
        isinstance(期望锚点, (list, tuple)) and len(期望锚点) == 0)
    用默认 = bool(无期望)
    if 无期望:
        词表 = list(全局锚点词表)
    elif isinstance(期望锚点, str):
        词表 = [期望锚点]
    else:
        词表 = [str(w) for w in 期望锚点]
    命中 = [w for w in 词表 if 锚点命中(回复, w, 口径)]
    分 = round(len(命中) / len(词表) * 100.0, 1) if 词表 else 0.0
    诊断 = {"期望锚点": 词表, "命中锚点": 命中, "使用默认全局词表": 用默认, "口径": 口径}
    return 分, 诊断


def 评口癖(回复):
    """维度 2：每百字 "啊"+"那个" 次数 c 的分段函数（spec 固定公式）。"""
    字数 = len(回复)
    啊次数 = 回复.count("啊")
    那个次数 = 回复.count("那个")
    c = (啊次数 + 那个次数) / 字数 * 100.0 if 字数 > 0 else 0.0
    if 字数 == 0 or c == 0:
        分 = 0.0
    elif c < 0.3:
        分 = round(c / 0.3 * 60.0, 1)
    elif c <= 8.0:
        分 = 100.0
    else:
        分 = round(max(0.0, 100.0 - (c - 8.0) * 10.0), 1)
    诊断 = {"啊次数": 啊次数, "那个次数": 那个次数, "字数": 字数, "每百字口癖c": round(c, 4)}
    return 分, 诊断


def 评五维(回复):
    """维度 3：五维人设符合度（0-100 代理）。温暖/戏谑/扩展加分，正式腔/AI 腔扣分。

    温暖词命中按"词表中各词出现次数之和"计数（≥2 记 30）；
    戏谑/能量标记按"出现处数"合计（≥3 记 30）；口癖扩展任一出现记 15；
    正式腔每处 -10、AI 腔每处 -20；总分限 [0, 100]。
    """
    温暖命中 = [w for w in 温暖词表 if w in 回复]
    温暖次数 = sum(回复.count(w) for w in 温暖词表)
    温暖得分 = 30 if 温暖次数 >= 2 else 0
    戏谑处数 = sum(回复.count(m) for m in 戏谑能量标记)
    戏谑得分 = 30 if 戏谑处数 >= 3 else 0
    扩展命中 = [w for w in 口癖扩展词表 if w in 回复]
    扩展得分 = 15 if 扩展命中 else 0
    正式处数 = sum(回复.count(w) for w in 正式腔词表)
    AI处数 = sum(回复.count(w) for w in AI腔词表)
    分 = round(max(0.0, min(100.0,
                            温暖得分 + 戏谑得分 + 扩展得分 - 10.0 * 正式处数 - 20.0 * AI处数)), 1)
    诊断 = {"温暖命中": 温暖命中, "温暖次数": 温暖次数, "温暖得分": 温暖得分,
            "戏谑能量处数": 戏谑处数, "戏谑得分": 戏谑得分,
            "口癖扩展命中": 扩展命中, "扩展得分": 扩展得分,
            "正式腔处数": 正式处数, "AI腔处数": AI处数}
    return 分, 诊断


def 评情感(回复, 期望情感=None):
    """维度 4：期望情感标签映射词组命中率。

    期望情感支持单标签字符串或多标签列表（列表时各标签词组合并去重）；
    期望为空或不识别 → 记 60（明细注明"无期望"）。
    """
    if 期望情感 is None:
        标签 = []
    elif isinstance(期望情感, str):
        标签 = [期望情感] if 期望情感.strip() else []
    elif isinstance(期望情感, (list, tuple)):
        标签 = [str(t) for t in 期望情感 if str(t).strip()]
    else:
        标签 = []
    有效组 = []
    已见 = set()
    for 标签名 in 标签:
        组 = 情感词组映射.get(标签名)
        if 组 and tuple(组) not in 已见:
            已见.add(tuple(组))
            有效组.append((标签名, 组))
    if not 有效组:
        return 60.0, {"期望情感": 期望情感, "命中情感组": [], "说明": "无期望"}
    命中组 = [标签名 for 标签名, 组 in 有效组 if any(w in 回复 for w in 组)]
    分 = round(len(命中组) / len(有效组) * 100.0, 1)
    诊断 = {"期望情感": 期望情感, "命中情感组": 命中组, "说明": ""}
    return 分, 诊断


def 评身份(回复, 提示=None, 自称词表=None):
    """维度 5：身份一致性。出戏短语每处扣 40；身份问句必须自称否则 0。

    无出戏且有自称 → 100；无身份问句且无出戏且无自称 → 90。
    自称词表默认 ["EmoCompanion", "EmoCompanion"]；日记基线模式传入含"我"的词表
    （日记为EmoCompanion第一人称自述，见文件头说明）。
    """
    词表 = list(自称词表) if 自称词表 else list(默认自称词表)
    出戏命中 = [p for p in 出戏短语表 if p in 回复]
    出戏次数 = sum(回复.count(p) for p in 出戏短语表)
    问句 = bool(提示) and any(m in 提示 for m in 身份问句标记)
    有自称 = any(s in 回复 for s in 词表)
    if 问句 and not 有自称:
        分 = 0.0
    else:
        基础分 = 100.0 if 有自称 else 90.0
        分 = round(max(0.0, 基础分 - 40.0 * 出戏次数), 1)
    诊断 = {"出戏命中": 出戏命中, "出戏次数": 出戏次数,
            "含自称": 有自称, "自称词表": 词表, "提示含身份问句": 问句}
    return 分, 诊断


def _四gram重复率(文本):
    """字符 4-gram 重复率 = Σ(出现次数-1) / 总 4-gram 数（len<4 时为 0）。"""
    if len(文本) < 4:
        return 0.0
    gram列表 = [文本[i:i + 4] for i in range(len(文本) - 3)]
    计数 = Counter(gram列表)
    重复量 = sum(n - 1 for n in 计数.values() if n > 1)
    return 重复量 / len(gram列表)


def 评流畅(回复):
    """维度 6：流畅性守卫。

    空 / 含 U+FFFD → 0；长度<8 → 20；单字符连续≥5 或 4gram 重复率>0.5 → 30；
    无硬伤 → max(30, 100 - min(40, 重复率×100))。
    """
    硬伤 = []
    if not 回复 or not 回复.strip():
        硬伤.append("空回复")
    if "\ufffd" in 回复:
        硬伤.append("含乱码替换符")
    字数 = len(回复)
    if 0 < 字数 < 8:
        硬伤.append("长度不足8")
    if re.search(r"(.)\1{4}", 回复):
        硬伤.append("单字符连续≥5")
    率 = _四gram重复率(回复)
    if 率 > 0.5:
        硬伤.append("4gram重复率超0.5")
    if 硬伤:
        if "空回复" in 硬伤 or "含乱码替换符" in 硬伤:
            分 = 0.0
        elif "长度不足8" in 硬伤:
            分 = 20.0
        else:
            分 = 30.0
    else:
        分 = round(max(30.0, 100.0 - min(40.0, 率 * 100.0)), 1)
    诊断 = {"字数": 字数, "硬伤": 硬伤, "4gram重复率": round(率, 4)}
    return 分, 诊断


