def 读回复jsonl(路径):
    """读取回复 jsonl（每行 {"编号","回复"}），按行序返回回复字符串列表。"""
    回复列表 = []
    with open(路径, "r", encoding="utf-8-sig") as f:  # utf-8-sig 兼容带 BOM 的文件
        for 行号, 行 in enumerate(f, 1):
            行 = 行.strip()
            if not 行:
                continue
            try:
                对象 = json.loads(行)
            except json.JSONDecodeError as 异常:
                raise ValueError("回复 jsonl 第 %d 行解析失败: %s" % (行号, 异常))
            回复列表.append(str(对象.get("回复", "")))
    return 回复列表


def 写json(路径, 数据):
    目录 = os.path.dirname(os.path.abspath(路径))
    if 目录:
        os.makedirs(目录, exist_ok=True)
    with open(路径, "w", encoding="utf-8") as f:
        json.dump(数据, f, ensure_ascii=False, indent=2)


def 打印汇总(汇总):
    print("-- 汇总 --")
    for 键, 值 in 汇总.items():
        print("  %s: %s" % (键, 值))


def 主():
    解析 = argparse.ArgumentParser(description="EmoCompanion角色一致性规则化六维评分器")
    解析.add_argument("--评估集", help="评估集 json（由 训练数据.py 生成）")
    解析.add_argument("--回复", help="回复 jsonl（每行 {\"编号\",\"回复\"}，与评估集等长对应）")
    解析.add_argument("--日记基线", help="EmoCompanion日记分档 json（对其 日记列表 逐篇评分）")
    解析.add_argument("--输出", help="结果输出 json 路径")
    解析.add_argument("--配置", help="系统配置 json 路径（默认取脚本同目录 系统配置.json）")
    解析.add_argument("--达标线", type=float, default=达标线默认, help="评估集达标线（默认 60）")
    参数 = 解析.parse_args()

    权重 = 获取权重(参数.配置)

    if 参数.日记基线:
        结果 = 评估日记基线(参数.日记基线, 权重=权重)
        print("日记基线：%s（%d 篇）" % (结果["源文件"], 结果["篇数"]))
        for 篇 in 结果["逐篇"]:
            print("  [%s] %s → 合成分 %.1f" % (篇["年龄段"], 篇["标题"], 篇["评估"]["合成分"]))
        打印汇总(结果["汇总"])
    elif 参数.评估集:
        if not os.path.exists(参数.评估集):
            print("评估集不存在: %s" % os.path.abspath(参数.评估集))
            print("评估集由训练数据管线生成：请先运行 python 训练数据.py 生成评估集"
                  "（默认输出 训练数据/评估集.json），再运行本命令。")
            sys.exit(2)
        if not 参数.回复:
            print("评估集模式需要 --回复 jsonl（每行 {\"编号\",\"回复\"}）")
            sys.exit(1)
        回复列表 = 读回复jsonl(参数.回复)
        结果 = 评估数据集(参数.评估集, 回复列表, 权重=权重, 达标线=参数.达标线)
        print("评估集：%s（%d 条）" % (结果["源文件"], 结果["条数"]))
        for 条 in 结果["明细"][:10]:
            print("  [%s] 合成分 %.1f%s" % (条["编号"], 条["评估"]["合成分"],
                                            "" if 条["达标"] else "（未达标）"))
        if 结果["条数"] > 10:
            print("  ... 其余 %d 条见输出文件" % (结果["条数"] - 10))
        打印汇总(结果["汇总"])
    else:
        解析.print_help()
        sys.exit(1)

    if 参数.输出:
        写json(参数.输出, 结果)
        print("已写出: %s" % os.path.abspath(参数.输出))


if __name__ == "__main__":
    主()
