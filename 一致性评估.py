# 日记基线模式
# ---------------------------------------------------------------------------
def 构造日记锚点(条目):
    """从日记条目"标题+话题"识别该篇期望锚点（全局词表+主题扩展词表）。

    识别不到任何锚点词时返回 None（回退全局词表）。
    """
    源文本 = str(条目.get("标题", "")) + str(条目.get("话题", ""))
    词表 = list(全局锚点词表) + list(日记主题锚点扩展词表)
    锚点 = [w for w in 词表 if w in 源文本]
    return 锚点 or None


def 评估日记基线(分档路径, 权重=None):
    """对 EmoCompanion_日记_分档.json 的 日记列表 逐篇评分，输出基线报告。

    每篇：期望情感=条目"情感标签"；期望锚点=该篇主题锚点（种子日记自证主题）；
    自称词表含"我"（第一人称自述，见文件头说明）；提示=日记标题。
    """
    with open(分档路径, "r", encoding="utf-8") as f:
        数据 = json.load(f)
    日记列表 = 数据.get("日记列表") if isinstance(数据, dict) else 数据
    if not isinstance(日记列表, list):
        raise ValueError("日记分档文件缺少 日记列表 数组: %s" % 分档路径)
    逐篇 = []
    for 条目 in 日记列表:
        期望锚点 = 构造日记锚点(条目)
        结果 = 评估单条(
            条目.get("正文", ""),
            期望情感=条目.get("情感标签"),
            期望锚点=期望锚点,
            提示=条目.get("标题"),
            权重=权重,
            自称词表=["EmoCompanion", "EmoCompanion", "我"],
        )
        逐篇.append({
            "标题": 条目.get("标题", ""),
            "年龄段": 条目.get("年龄段", ""),
            "日期": 条目.get("日期", ""),
            "话题": 条目.get("话题", ""),
            "期望锚点": 期望锚点 if 期望锚点 else "(回退全局词表)",
            "评估": 结果,
        })
    return {
        "模式": "日记基线",
        "源文件": os.path.abspath(分档路径),
        "篇数": len(逐篇),
        "逐篇": 逐篇,
        "汇总": 汇总统计([p["评估"] for p in 逐篇]),
    }


