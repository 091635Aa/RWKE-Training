# 汇总统计
# ---------------------------------------------------------------------------
def 汇总统计(结果列表, 达标线=None):
    """各维均值 + 合成分均值/最小值 +（可选）达标线判定。"""
    n = len(结果列表)
    汇总 = {}
    for 键 in _维度键:
        值 = [r[键] for r in 结果列表]
        汇总[键 + "_均值"] = round(sum(值) / n, 1) if n else 0.0
    汇总["合成分_最小值"] = round(min((r["合成分"] for r in 结果列表)), 1) if n else 0.0
    if 达标线 is not None:
        达标数 = sum(1 for r in 结果列表 if r["合成分"] >= 达标线)
        汇总["达标线"] = 达标线
        汇总["达标数"] = 达标数
        汇总["达标率"] = round(达标数 / n * 100.0, 1) if n else 0.0
    return 汇总


