def 加载权重(配置路径=None):
    """读取 系统配置.json 的 微调.六维权重 覆盖内置默认权重。

    缺失 / 文件读取失败 / 键不全 / 数值越界 / 和不为 1（容差 1e-6）时，
    一律回退内置默认权重。只读配置，绝不修改任何既有文件。
    """
    路径 = 配置路径 or os.path.join(os.path.dirname(os.path.abspath(__file__)), "系统配置.json")
    try:
        with open(路径, "r", encoding="utf-8") as f:
            配置 = json.load(f)
        权 = 配置.get("微调", {}).get("六维权重") if isinstance(配置, dict) else None
        if not isinstance(权, dict):
            print("[权重] 配置缺 微调.六维权重，使用内置默认权重（%s）" % 路径)
            return dict(默认权重)
        规整 = {}
        for 键 in 默认权重:
            if 键 not in 权:
                raise ValueError("六维权重缺键: %s" % 键)
            值 = float(权[键])
            if not (0.0 <= 值 <= 1.0):
                raise ValueError("权重越界: %s=%s" % (键, 值))
            规整[键] = 值
        总和 = sum(规整.values())
        if abs(总和 - 1.0) > 1e-6:
            raise ValueError("六维权重之和 %s 不为 1" % 总和)
        print("[权重] 已从 %s 读取 微调.六维权重" % 路径)
        return 规整
    except FileNotFoundError:
        print("[权重] 未找到配置 %s，使用内置默认权重" % 路径)
        return dict(默认权重)
    except Exception as 异常:
        print("[权重] 配置读取/校验失败（%s），使用内置默认权重" % 异常)
        return dict(默认权重)


def 获取权重(配置路径=None):
    """带缓存的权重获取（同一配置只读一次文件，保证过程确定且高效）。"""
    键 = 配置路径 or "__默认__"
    if 键 not in _权重缓存:
        _权重缓存[键] = 加载权重(配置路径)
    return _权重缓存[键]


 
