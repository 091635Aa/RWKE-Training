def 评估单条(回复, 期望情感=None, 期望锚点=None, 提示=None, 权重=None, 自称词表=None):
    """对单条回复做六维评分，返回各维分（0-100，1 位小数）+ 合成分 + 诊断明细。"""
    w = 权重 or 获取权重()
    回复 = str(回复) if 回复 is not None else ""
    锚分, 锚诊 = 评锚点(回复, 期望锚点)
    口分, 口诊 = 评口癖(回复)
    五分, 五诊 = 评五维(回复)
    情分, 情诊 = 评情感(回复, 期望情感)
    身分, 身诊 = 评身份(回复, 提示, 自称词表)
    流分, 流诊 = 评流畅(回复)
    合成 = round(w["锚点"] * 锚分 + w["口癖"] * 口分 + w["五维"] * 五分
                 + w["情感"] * 情分 + w["身份"] * 身分 + w["流畅"] * 流分, 1)
    return {
        "锚点命中率": 锚分,
        "口癖率": 口分,
        "五维人设符合度": 五分,
        "情感基调匹配": 情分,
        "身份一致性": 身分,
        "流畅性守卫": 流分,
        "合成分": 合成,
        "诊断": {"锚点": 锚诊, "口癖": 口诊, "五维": 五诊,
                 "情感": 情诊, "身份": 身诊, "流畅": 流诊},
    }


