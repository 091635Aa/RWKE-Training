# 评估集模式
# ---------------------------------------------------------------------------
def 评估数据集(评估集路径, 回复列表, 权重=None, 达标线=达标线默认):
    """评估集 JSON 数组 [{"编号","提示","期望情感","期望锚点"}] 与等长回复列表逐条对应评分。

    返回 per-item 明细 + 汇总（各维均值、合成分均值/最小值、达标线判定）。
    评估集文件不存在时抛 FileNotFoundError（CLI 层负责打印指引并退出码 2）。
    """
    if not os.path.exists(评估集路径):
        raise FileNotFoundError(
            "评估集不存在: %s ；请先运行 python 训练数据.py 生成（本脚本不负责生成评估集）" % 评估集路径)
    with open(评估集路径, "r", encoding="utf-8") as f:
        评估集 = json.load(f)
    if not isinstance(评估集, list):
        raise ValueError("评估集应为 JSON 数组: %s" % 评估集路径)
    if len(回复列表) != len(评估集):
        raise ValueError("回复条数 %d 与评估集条数 %d 不等" % (len(回复列表), len(评估集)))
    明细 = []
    for 条目, 回复 in zip(评估集, 回复列表):
        结果 = 评估单条(
            回复,
            期望情感=条目.get("期望情感") if isinstance(条目, dict) else None,
            期望锚点=条目.get("期望锚点") if isinstance(条目, dict) else None,
            提示=条目.get("提示") if isinstance(条目, dict) else None,
            权重=权重,
        )
        明细.append({
            "编号": 条目.get("编号") if isinstance(条目, dict) else None,
            "提示": 条目.get("提示") if isinstance(条目, dict) else None,
            "期望情感": 条目.get("期望情感") if isinstance(条目, dict) else None,
            "期望锚点": 条目.get("期望锚点") if isinstance(条目, dict) else None,
            "回复": 回复,
            "达标": 结果["合成分"] >= 达标线,
            "评估": 结果,
        })
    return {
        "模式": "评估集",
        "源文件": os.path.abspath(评估集路径),
        "条数": len(明细),
        "达标线": 达标线,
        "明细": 明细,
        "汇总": 汇总统计([d["评估"] for d in 明细], 达标线),
    }


